def materialise_t3(dest: str | Path) -> Path:
    """Write the existing Node/Express app that T3's 'for my app' refers to."""
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    for rel, body in T3_FILES.items():
        f = dest / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(body, encoding="utf-8")
    return dest



