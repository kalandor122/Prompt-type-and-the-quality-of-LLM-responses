"""Build report.md from data/sales.csv."""
import csv
from collections import defaultdict

totals = defaultdict(float)
with open("data/sales.csv", newline="", encoding="utf-8") as f:
    for row in csv.DictReader(f):
        totals[row["month"]] += float(row["revenue"])

with open("report.md", "w", encoding="utf-8") as f:
    f.write("# Monthly revenue report\n\n")
    f.write("| Month | Revenue |\n|---|---|\n")
    for month in sorted(totals):
        f.write(f"| {month} | {totals[month]:.2f} |\n")
    f.write("\n_Generated by report.py._\n")
print("report.md written")
